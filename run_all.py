"""Reproduce every number and chart in the README and on the website.

    pip install -r requirements.txt
    python -m src.fetch     # downloads (a few minutes)
    python run_all.py       # writes results/
"""
import warnings

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from src import config as C
from src import muni
from src import report as RP
from src.metrics import split_table, stats

warnings.filterwarnings("ignore")
OUT = C.RESULTS
SPLITS = [("train 2008-17", *C.TRAIN), ("test 2018-26", *C.TEST)]
SUB = [("2008-12", "2008", "2012"), ("2013-17", "2013", "2017"), ("2018-21", "2018", "2021"), ("2022-26", "2022", "2026")]
INK, MUTED, BLUE, ORANGE, GREEN, RED, PURPLE = "#1f2937", "#9ca3af", "#2563eb", "#f59e0b", "#059669", "#dc2626", "#7c3aed"


def md(df, fmt=".2f"):
    return df.to_markdown(floatfmt=fmt)


def style(ax):
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.grid(axis="y", color="#e5e7eb", lw=0.6)


def main():
    rep = ["# Results (auto-generated by run_all.py)\n"]
    print("muni ...")
    m_daily = muni.run()
    weekly = pd.DataFrame({"muni": m_daily.resample("W-FRI").sum(min_count=1)}).loc["2008":]

    # ------------------------------------------------ muni deep dive
    beta = muni.same_day_vs_total_beta()
    rep += ["\n## Evidence of the lag\n", md(beta, ".3f"), "\n"]
    rob = {}
    rob["base (open entry, 1bp + hedge)"] = m_daily
    for cm in (2, 3):
        rob[f"costs x{cm}"] = muni.run(cost_mult=cm)
    for comp in (["catch_up"], ["catch_up", "risk"], ["catch_up", "risk", "calendar"], ["calendar"], ["flow"], ["risk"]):
        rob["only " + "+".join(comp)] = muni.run(components=comp, params={"band": 0.0} if comp == ["calendar"] else None)
    for hl in (2, 3, 5, 8):
        rob[f"half-life {hl}d"] = muni.run(params={"halflife": hl})
    for bw in (0.0, 0.5, 1.0):
        rob[f"band {bw}"] = muni.run(params={"band": bw})
    rob["catch_up+risk, drivers lagged 1y (placebo)"] = muni.run(components=["catch_up", "risk"], driver_shift=250)
    for e in C.MUNI_ETFS:
        rob[f"single ETF {e}"] = muni.run_one(e)["pnl"]
    t_rob = split_table(rob, 252, SPLITS + SUB)
    t_rob.to_csv(OUT / "muni_robustness.csv")
    print(md(t_rob))
    yearly = m_daily.groupby(m_daily.index.year).apply(lambda x: stats(x, 252)["sharpe"])
    rep += ["\n### Robustness (daily, net)\n", md(t_rob), "\n\n### Sharpe by calendar year\n", md(yearly.to_frame("sharpe").T), "\n"]

    # ------------------------------------------------ charts
    ir = muni.impulse_response()
    full_ief = 1.0
    fig, axs = plt.subplots(1, 2, figsize=(11, 4.2))
    for e, c in zip(C.MUNI_ETFS, [BLUE, ORANGE]):
        axs[0].plot(ir.index, ir[e], marker="o", ms=3, color=c, label=e)
    axs[0].set_xlabel("trading days after a +1 sd Treasury (IEF) move")
    axs[0].set_ylabel("cumulative muni ETF response, bp")
    axs[0].set_title("Munis absorb Treasury moves over days, not hours", loc="left", fontsize=10)
    axs[0].legend(frameon=False)
    style(axs[0])
    yv = yearly.dropna()
    axs[1].bar(yv.index.astype(str), yv.values, color=[BLUE if v > 0 else RED for v in yv.values])
    axs[1].set_title("Sharpe ratio by year (net, next-open entry)", loc="left", fontsize=10)
    axs[1].tick_params(axis="x", rotation=90, labelsize=8)
    style(axs[1])
    fig.tight_layout()
    fig.savefig(OUT / "muni_evidence.png", dpi=150)
    plt.close(fig)

    # live positions
    live = {}
    for e in C.MUNI_ETFS:
        d = muni.run_one(e)
        live[e] = dict(date=str(d.index[-1].date()), position=round(d.pos.iloc[-1], 2),
                       catch_up=round(d.catch_up.iloc[-1], 2), risk=round(d.risk.iloc[-1], 2),
                       flow=round(d.flow.iloc[-1], 2), hedge_beta=round(d.beta.iloc[-1], 3))
    rep += ["\n## Latest muni positions (units of risk; + = long muni ETF vs IEF hedge)\n",
            md(pd.DataFrame(live).T, ".2f"), "\n"]
    # ------------------------------------------------ tearsheet
    splits = [("2008-17 (design)", *C.TRAIN), ("2018-26 (out-of-sample)", *C.TEST)]
    muni_r = RP.vol_target(weekly["muni"].dropna())
    kpi = RP.metrics_table(muni_r, splits)
    kpi.to_csv(OUT / "kpi_muni.csv")
    RP.tearsheet(muni_r, OUT / "tearsheet.png",
                 f"Muni lag strategy: Sharpe {RP.metrics(muni_r)['Sharpe']:.2f}, net of costs, 10% vol target", C.TEST[0])
    RP.monthly_heatmap(muni_r, OUT / "monthly_returns.png", "Monthly returns (%), 10% vol target")
    RP.robustness_bars(t_rob, OUT / "robustness.png")
    annual = muni_r.groupby(muni_r.index.year).apply(lambda x: (1 + x).prod() - 1)
    annual.to_frame("return").to_csv(OUT / "annual_returns.csv")
    rep += ["\n## KPIs (weekly, ex-ante 10% vol target)\n", md(kpi), "\n\n## Calendar-year returns\n", md(annual.to_frame("return"), ".3f"), "\n"]
    print(md(kpi))
    (OUT / "report.md").write_text("\n".join(rep))
    weekly.to_csv(OUT / "weekly_returns.csv")
    print("done")


if __name__ == "__main__":
    main()
